"""Transactional SQLite (local) and Neon/PostgreSQL connections."""
import os
import sqlite3

import psycopg
from psycopg.rows import dict_row

INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)
DATABASE_ERRORS = (sqlite3.DatabaseError, psycopg.Error)


class ConfigurationError(RuntimeError):
    pass


def configured_url():
    return os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL") or ""


class PostgresCursor:
    def __init__(self, cursor):
        self.raw = cursor

    def execute(self, query, parameters=()):
        # Repository queries use qmark parameters; values always stay bound.
        self.raw.execute(query.replace("?", "%s"), parameters)
        return self

    def fetchone(self):
        return self.raw.fetchone()

    def fetchall(self):
        return self.raw.fetchall()


class PostgresConnection:
    is_postgres = True

    def __init__(self, raw):
        self.raw = raw

    def cursor(self):
        return PostgresCursor(self.raw.cursor())

    def execute(self, query, parameters=()):
        return self.cursor().execute(query, parameters)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect(url, sqlite_path, hosted=False):
    if url:
        if not url.startswith(("postgresql://", "postgres://")):
            raise ConfigurationError("DATABASE_URL must be a PostgreSQL connection URL.")
        return PostgresConnection(psycopg.connect(
            url, row_factory=dict_row, connect_timeout=10, prepare_threshold=None))
    if hosted:
        raise ConfigurationError("Connect a Neon database and configure DATABASE_URL for hosted accounts.")
    conn = sqlite3.connect(sqlite_path, timeout=10)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def init_schema(conn):
    postgres = getattr(conn, "is_postgres", False)
    if postgres:
        # Serialize first-use DDL across serverless instances, within this transaction.
        conn.execute("SELECT pg_advisory_xact_lock(782139420)")
    identity = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if postgres else "INTEGER PRIMARY KEY AUTOINCREMENT"
    binary = "BYTEA" if postgres else "BLOB"
    user_id_type = "BIGINT" if postgres else "INTEGER"
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS users (
            id {identity}, username TEXT NOT NULL,
            password_hash TEXT NOT NULL, avatar_url TEXT DEFAULT '',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (LOWER(username))")
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS progress (
            user_id {user_id_type} PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
            progress_json TEXT NOT NULL DEFAULT '{{}}',
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("CREATE TABLE IF NOT EXISTS auth_settings (name TEXT PRIMARY KEY, value TEXT NOT NULL)")
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS auth_sessions (
            token_id TEXT PRIMARY KEY,
            user_id {user_id_type} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            expires_at BIGINT NOT NULL
        )
    """)
    conn.execute("CREATE INDEX IF NOT EXISTS auth_sessions_expiry ON auth_sessions (expires_at)")
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS avatars (
            filename TEXT PRIMARY KEY,
            user_id {user_id_type} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            data {binary} NOT NULL, content_type TEXT NOT NULL
        )
    """)
